export function generateCurriculumExam(options: GeneratorOptions): ExamSet {
  const { grade, subject, topic, questionCount, difficulty, termType } = options;

  // Determine subject key
  let subjectKey = 'science';
  if (subject.includes('คณิต')) subjectKey = 'math';
  else if (subject.includes('ไทย')) subjectKey = 'thai';
  else if (subject.includes('อังกฤษ') || subject.toLowerCase().includes('english')) subjectKey = 'math';
  else subjectKey = 'science';

  const pool = SUBJECT_QUESTION_BANKS[subjectKey] || SUBJECT_QUESTION_BANKS.science;
  const questions: Question[] = [];

  const needed = Math.min(Math.max(questionCount, 5), 40);

  // Generate varied questions
  for (let i = 0; i < needed; i++) {
    const template = pool[i % pool.length];
    const qNum = i + 1;

    // Shuffle choices slightly to randomize correct answer among ก, ข, ค, ง
    const baseChoices = [...template.choices];
    const targetKeyIndex = i % 4; // 0=ก, 1=ข, 2=ค, 3=ง
    const correctText = baseChoices[0];
    const wrongChoices = baseChoices.slice(1);

    // Reconstruct choices with targetKeyIndex receiving the correct answer
    const finalChoicesTexts = new Array(4).fill('');
    finalChoicesTexts[targetKeyIndex] = correctText;
    let wrongIdx = 0;
    for (let c = 0; c < 4; c++) {
      if (c !== targetKeyIndex) {
        finalChoicesTexts[c] = wrongChoices[wrongIdx % wrongChoices.length] || `ตัวเลือกเสริมที่ ${c + 1}`;
        wrongIdx++;
      }
    }

    const keys: ('ก' | 'ข' | 'ค' | 'ง')[] = ['ก', 'ข', 'ค', 'ง'];
    const correctLetter = keys[targetKeyIndex];

    questions.push({
      id: `q-fallback-${Date.now()}-${qNum}`,
      number: qNum,
      question: pool.length > i ? template.q : `(ข้อ ${qNum}) ${template.q} [ทบทวนบทเรียน ${topic}]`,
      choices: keys.map((key, idx) => ({
        key,
        text: finalChoicesTexts[idx],
      })),
      correctAnswer: correctLetter,
      explanation: template.exp,
      teachingTip: template.tip || `เน้นย้ำให้นักเรียนวิเคราะห์โจทย์ข้อนี้อย่างรอบคอบตามระดับชั้น ${grade}`,
      topic,
    });
  }

  return {
    id: `exam-${Date.now()}`,
    title: `ชุดข้อสอบมาตรฐาน ${subject} ${grade}: ${topic}`,
    grade,
    subject,
    subjectId: (options.subjectId || 'science') as SubjectId,
    topic,
    difficulty: difficulty as any,
    termType: termType as any,
    totalQuestions: questions.length,
    questions,
    createdAt: new Date().toISOString().split('T')[0],
    timerPerQuestion: 60,
  };
}
